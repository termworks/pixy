static bool in_ranges(unsigned int code, const Range *ranges, size_t count) {
    size_t low = 0, high = count;
    while (low < high) {
        size_t mid = (low + high) / 2;
        if (code < ranges[mid].first) {
            high = mid;
        } else if (code > ranges[mid].last) {
            low = mid + 1;
        } else {
            return true;
        }
    }
    return false;
}

int pixy_code_width(unsigned int code) {
    if (code == 0) return 0;
    if (code < 0x20 || (code >= 0x7F && code < 0xA0)) return 0;
    if (code < 0x300) return 1;
    if (in_ranges(code, ZERO, sizeof(ZERO) / sizeof(ZERO[0]))) return 0;
    if (in_ranges(code, WIDE, sizeof(WIDE) / sizeof(WIDE[0]))) return 2;
    return 1;
}

static size_t decode(const unsigned char *bytes, size_t len, unsigned int *out) {
    unsigned char first = bytes[0];
    if (first < 0x80) {
        *out = first;
        return 1;
    }
    size_t need;
    unsigned int code;
    if ((first & 0xE0) == 0xC0) {
        need = 2;
        code = first & 0x1Fu;
    } else if ((first & 0xF0) == 0xE0) {
        need = 3;
        code = first & 0x0Fu;
    } else if ((first & 0xF8) == 0xF0) {
        need = 4;
        code = first & 0x07u;
    } else {
        *out = 0xFFFD;
        return 1;
    }
    if (len < need) {
        *out = 0xFFFD;
        return 1;
    }
    for (size_t i = 1; i < need; i++) {
        if ((bytes[i] & 0xC0) != 0x80) {
            *out = 0xFFFD;
            return 1;
        }
        code = (code << 6) | (bytes[i] & 0x3Fu);
    }
    *out = code;
    return need;
}

size_t pixy_cell_width(const char *text, size_t len) {
    const unsigned char *bytes = (const unsigned char *)text;
    size_t total = 0, at = 0;
    while (at < len) {
        unsigned int code = 0;
        at += decode(bytes + at, len - at, &code);
        total += (size_t)pixy_code_width(code);
    }
    return total;
}
