/* Terminal cell width.
 *
 * Not libc's wcwidth: that answers from the process locale, so a prompt would
 * measure differently on a machine without a UTF-8 locale and lay itself out
 * wrong. The table is here, it is the same one the Rust build used through the
 * unicode-width crate, and tests/width_parity.txt pins it.
 */
#include "pixy.h"

